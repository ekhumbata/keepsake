#!/usr/bin/env python3
"""Regenerates every bitmap font the firmware uses, from the vendored font files.

    pip install -r tools/requirements.txt
    python3 tools/generate_keepsake_fonts.py

- Interface: Nunito (fonts/nunito), symbols kUi<size><SemiBold|Bold|Black>
- Book text: Literata (fonts/literata), symbols kBook<size><Regular|Bold|Italic>

The vendored files are the families' original variable fonts, unmodified (each folder keeps
its OFL.txt). The weight/optical-size instances needed here are made in a temporary folder at
generation time, so no modified font file is ever committed. That matters for Quicksand
(fonts/quicksand, ready for #104): its licence reserves the name "Quicksand" for unmodified
versions.

Writes firmware/components/core/epaper_ui/generated_epaper_fonts.cpp and its header.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import generate_epaper_fonts as gen  # noqa: E402

try:
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
except ImportError as exc:  # pragma: no cover
    raise SystemExit("needs fonttools: pip install -r tools/requirements.txt") from exc

UI_SIZES = [22, 26, 32, 38, 46, 55, 165]
UI_WEIGHTS = [("SemiBold", 600), ("Bold", 700), ("Black", 900)]
BOOK_SIZES = [22]
BOOK_STYLES = [
    ("Regular", "Literata[opsz,wght].ttf", 400),
    ("Bold", "Literata[opsz,wght].ttf", 700),
    ("Italic", "Literata-Italic[opsz,wght].ttf", 400),
]
# Literata's optical-size axis is in points; reading text on this panel wants the text cut.
BOOK_OPTICAL_SIZE = 12

OUT_SOURCE = ROOT / "firmware/components/core/epaper_ui/generated_epaper_fonts.cpp"
OUT_HEADER = ROOT / "firmware/components/core/epaper_ui/include/epaper_ui/generated_epaper_fonts.h"


def instance(source: Path, out: Path, axes: dict[str, float]) -> Path:
    font = TTFont(str(source))
    limits = {axis.axisTag: (axis.minValue, axis.maxValue) for axis in font["fvar"].axes}
    clamped = {tag: max(limits[tag][0], min(limits[tag][1], value))
               for tag, value in axes.items() if tag in limits}
    instancer.instantiateVariableFont(font, clamped, inplace=True)
    font.save(str(out))
    return out


def main() -> int:
    specs: list[gen.FontSpec] = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        for name, weight in UI_WEIGHTS:
            path = instance(ROOT / "fonts/nunito/Nunito[wght].ttf",
                            tmp_dir / f"Nunito-{name}.ttf", {"wght": weight})
            for size in UI_SIZES:
                specs.append(gen.FontSpec(str(path), f"kUi{size}{name}", size))
        for name, file_name, weight in BOOK_STYLES:
            path = instance(ROOT / "fonts/literata" / file_name, tmp_dir / f"Literata-{name}.ttf",
                            {"wght": weight, "opsz": BOOK_OPTICAL_SIZE})
            for size in BOOK_SIZES:
                specs.append(gen.FontSpec(str(path), f"kBook{size}{name}", size))
        specs.sort(key=lambda s: s.symbol)
        OUT_SOURCE.write_text(gen.generate_source(specs), encoding="utf-8")

    lines = [
        "// Generated by tools/generate_keepsake_fonts.py -- do not edit.",
        "#ifndef GENERATED_EPAPER_FONTS_H",
        "#define GENERATED_EPAPER_FONTS_H",
        "",
        '#include "epaper_ui/bitmap_font.h"',
        "",
        "namespace epaper_fonts {",
        "",
        *[f"extern const epaper_font::BitmapFont {spec.symbol};" for spec in specs],
        "",
        "}  // namespace epaper_fonts",
        "",
        "#endif  // GENERATED_EPAPER_FONTS_H",
        "",
    ]
    OUT_HEADER.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(specs)} fonts to {OUT_SOURCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
